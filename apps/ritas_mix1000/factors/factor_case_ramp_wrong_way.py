class FactorCaseRampWrongWay(Factor):
    NAME = 'F_CaseHighwayWrongWay'

    MAP_SPAWN_POINT_MAPPING = {
        'Carla/Maps/Town04': {
            'ego': 110,
            'npc': [108, 113, 114, 117]
        },
    }

    def __init__(
        self, context: CarlaContext, ego: CarlaVehicle, *,
        distance_offset: float = 15.0,
        lateral_offset: float = 1.5,
        act_speed_kmh: float = 30.0,
        act_brake_distance: float = 30.0,
        target_speed_kmh: float = 100.0,
        act_start_delay_seconds: float = 5.0,
        random_right_lanechange_percentage: float = 100.0,
        vehicle_lane_offset: float = 0.2,
        act_stop_distance: float = 10.0,
    ):
        super().__init__(context)
        self._ego = ego
        self._act: CarlaVehicle | None = None
        self._distance_offset = distance_offset
        self._lateral_offset = lateral_offset
        self._act_speed_kmh = act_speed_kmh
        self._act_brake_distance = act_brake_distance
        self._act_braking = False
        self._vehicles: list[CarlaVehicle] = []
        self._act_tf_index = [0]  # 用于跟踪当前TF记录的索引
        self._act_start_delay_ticks = int(act_start_delay_seconds * context.fps)  # 延迟启动的tick数
        self._current_ticks = 0  # 当前tick计数
        self._random_right_lanechange_percentage = random_right_lanechange_percentage
        self._vehicle_lane_offset = vehicle_lane_offset
        self._act_stop_distance = act_stop_distance
        self._act_stopped = False  # 标记act是否已停止更新

    @property
    def ego(self) -> CarlaVehicle:
        return self._ego

    @property
    def act(self) -> CarlaVehicle:
        return self._act

    def setup(self) -> None:
        spawn_point_mapping = self.MAP_SPAWN_POINT_MAPPING[self._context.map_name]
        # 设置 ego 位置
        tf_ego = self._context.spawn_points[spawn_point_mapping['ego']]
        self._ego.actor.set_transform(tf_ego)
        self._vehicles.append(self._ego)

        # 使用TF_RECORDS的第一个记录创建act
        if len(TF_RECORDS) > 0:
            initial_tf_data = CarlaTransform.deserialize(TF_RECORDS[0])
            initial_tf = initial_tf_data.to_carla()
            initial_tf.location.z += 0.1  # 稍微抬高避免碰撞
            
            self._act = self._context.actors.create_vehicle(
                bp=CarlaBlueprints.VEHICLE_TESLA_MODEL3,
                tf=initial_tf,
                name='ACT',
            )
            self._act.spawn(self._context.world)
            self._vehicles.append(self._act)
            
            # 开启act的双闪灯
            if self._act.actor is not None and self._act.actor.is_alive:
                combined_light_state = carla.VehicleLightState.RightBlinker | carla.VehicleLightState.LeftBlinker
                self._act.actor.set_light_state(carla.VehicleLightState(combined_light_state))
                self.logger.info('ACT hazard lights enabled (RightBlinker + LeftBlinker)')
        else:
            self.logger.error('No TF records found, cannot create ACT')
            return super().setup()

        # 创建 npc
        for npc_sp_idx in spawn_point_mapping['npc']:
            npc_tf = self._context.spawn_points[npc_sp_idx]
            npc = self._context.actors.create_vehicle(
                bp=CarlaBlueprints.VEHICLE_MERCEDES_SPRINTER,
                tf=npc_tf,
                name=f'NPC_{npc_sp_idx}',
            )
            npc.spawn(self._context.world, ignore_spawn_failure=True)
            self._vehicles.append(npc)

        self._context.tick()
        self._context.actors.wait_stable()

        # 使用 Traffic Manager 控制车辆
        tm = self._context.traffic_manager
        target_speed_kmh = 90.0
        target_speed_ms = target_speed_kmh / 3.6
        
        # ego向右变道并右转进入匝道
        if self._ego.actor is not None and self._ego.actor.is_alive:
            tm.set_route(self._ego.actor, ['Right', 'Right'])
            self._ego.set_carla_autopilot(enable=True)
            tm.set_desired_speed(self._ego.actor, target_speed_ms)
            self.logger.info('EGO route set to Right')
        
        # 其他车辆直行
        for vehicle in self._vehicles:
            if vehicle != self._ego and vehicle != self._act:  # act不启动autopilot
                tm.auto_lane_change(vehicle.actor, False)
                vehicle.set_carla_autopilot(enable=True)
                tm.set_desired_speed(vehicle.actor, target_speed_ms)
        
        # act禁用autopilot，由tick中的回放逻辑控制
        if self._act is not None and self._act.actor is not None and self._act.actor.is_alive:
            self._act.set_carla_autopilot(enable=False)
        
        self.logger.info(f'All vehicles (except ACT) target speed set to {target_speed_kmh:.1f} km/h')
        return super().setup()

    def tick(self) -> None:
        if self._act is None or self._act.actor is None or not self._act.actor.is_alive:
            self._current_ticks += 1
            return super().tick()
        
        # 检查是否已经过了延迟时间
        if self._current_ticks < self._act_start_delay_ticks:
            self._current_ticks += 1
            return super().tick()
        
        # 延迟时间已过，开始act的逆向回放逻辑
        if self._current_ticks == self._act_start_delay_ticks:
            self.logger.info(f'ACT replay started after {self._act_start_delay_ticks / self._context.fps:.1f} seconds delay')
        
        # 检查act和ego之间的距离
        if not self._act_stopped and self._ego.actor is not None and self._ego.actor.is_alive:
            ego_location = self._ego.actor.get_location()
            act_location = self._act.actor.get_location()
            distance = ego_location.distance(act_location)
            
            if distance < self._act_stop_distance:
                self._act_stopped = True
                self.logger.info(f'ACT stopped updating at distance {distance:.2f}m (threshold: {self._act_stop_distance}m)')
        
        # 如果act未停止，继续更新TF记录
        if not self._act_stopped:
            # 每帧读取下一个TF记录并设置transform
            if self._act_tf_index[0] < len(TF_RECORDS):
                try:
                    # 读取下一个TF记录
                    tf_data = CarlaTransform.deserialize(TF_RECORDS[self._act_tf_index[0]])
                    carla_tf = tf_data.to_carla()
                    
                    # 设置act的transform
                    self._act.actor.set_transform(carla_tf)
                    
                    # 递增索引
                    self._act_tf_index[0] += 1
                    
                except Exception as e:
                    self.logger.error(f'Failed to replay ACT TF at index {self._act_tf_index[0]}: {e}')
            else:
                # 所有TF记录已回放完毕
                if self._act_tf_index[0] == len(TF_RECORDS):
                    self.logger.warning('All ACT TF records replayed. ACT will remain at its last position.')
                    self._act_tf_index[0] += 1  # 避免重复警告
        
        self._current_ticks += 1
        return super().tick()

    def teardown(self) -> None:
        # 禁用 Traffic Manager 控制的 autopilot
        if self._ego.actor is not None and self._ego.actor.is_alive:
            self._ego.set_carla_autopilot(enable=False)
        if self._act is not None and self._act.actor is not None and self._act.actor.is_alive:
            self._act.set_carla_autopilot(enable=False)
            self._act.destroy()
        return super().teardown()